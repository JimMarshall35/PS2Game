static struct MemoryAllocation gAllocations[128];

static size_t gNumAllocations = 0;

/////////////////////////////////////////////////////////////////////////////////////////// Public Globals

/////////////////////////////////////////////////////////////////////////////////////////// Private Functions

/////////////////////////////////////////////////////////////////////////////////////////// Public Functions

void* Mem_malloc(size_t size, const char* purpose)
{
    void* pRet = malloc(size);

    size_t i = gNumAllocations++;
    gAllocations[i] = (struct MemoryAllocation) {
        .pAddress = pRet,
        .size = size
    };
    strcpy(gAllocations[i].purpose, purpose);

    return pRet;
}

size_t Mem_GetNumAllocations()
{
    return gNumAllocations;
}

struct MemoryAllocation* Mem_GetAllocationInfo(size_t i)
{
    if(i >= gNumAllocations)
    {
        return NULL;
    }
    return &gAllocations[i];
}


void* Mem_AlignUp(void* ptr, size_t align) {
    uintptr_t p = (uintptr_t)ptr;
    uintptr_t aligned = (p + (align - 1)) & ~(align - 1);
    return (void*)aligned;
}

void* Mem_AlignDown(void* ptr, size_t align) {
    uintptr_t p = (uintptr_t)ptr;
    uintptr_t aligned = p & ~(align - 1);
    return (void*)aligned;
}